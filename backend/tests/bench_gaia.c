/* bench_gaia.c — GAIA-style mini benchmark (Levels 1 & 2 patterns).
 *
 * GAIA evaluates: multi-step tool use, cross-file reasoning, document parsing,
 * (Level 3 adds long-horizon web/GUI work — out of scope, see report). Tasks
 * here mirror GAIA task *shapes* reachable with cognitive-os-agent's tools:
 *   L1: single-file / single-fact extraction and arithmetic
 *   L2: multi-file joins, filtering, aggregation
 * plus one LLM-layer vision task (image understanding, requires a multimodal
 * model — run with --vision; skipped otherwise since deepseek-chat is
 * text-only).
 *
 * Scoring: GAIA official normalization — lowercase, strip punctuation, drop
 * articles (a/an/the), collapse whitespace — then exact match against the
 * expected answer (whole response or its final line). Numeric fallback: if
 * both sides parse as float and are equal, count as correct ("42.50"=="42.5").
 *
 * Fixtures: csv/txt written by this binary; docx/png generated by
 * tools/gen_gaia_fixtures.py (skipped → task SKIP, not FAIL).
 *
 * Modes: --real (default, COA_LLM_* env) / --mock / --vision (adds image task).
 */
