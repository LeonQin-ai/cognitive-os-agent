static int run_python_fixtures(void) {
    if (system("python3 tools/gen_gaia_fixtures.py " FIXDIR " > gaia_fixtures.log 2>&1") != 0 &&
        system("python tools/gen_gaia_fixtures.py " FIXDIR " >> gaia_fixtures.log 2>&1") != 0)
        return 0;
    char full[1024];
    coa_path_resolve(full, sizeof(full), FIXDIR, "contact.docx");
    if (coa_fs_read_file(full)) return 1;
    return 0;
}

/* ---- vision task (LLM layer; needs a multimodal model) ---- */
static int vision_task(coa_llm *llm, char **answer_out) {
    char full[1024];
    coa_path_resolve(full, sizeof(full), FIXDIR, "diagram.png");
    FILE *f = fopen(full, "rb");
    if (!f) return -1;
    fseek(f, 0, SEEK_END);
    long len = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (len <= 0) { fclose(f); return -1; }
    unsigned char *png = (unsigned char *)malloc((size_t)len);
    if (!png || fread(png, 1, (size_t)len, f) != (size_t)len) {
        free(png);
        fclose(f);
        return -1;
    }
    fclose(f);
    char *b64 = coa_base64_encode(png, (size_t)len);
    free(png);
    if (!b64) return -1;
    coa_llm_message msgs[1] = {
        {"user", "What is the 4-digit access code shown in the image? Answer with the digits only.", b64, "image/png"},
    };
    coa_llm_request req;
    memset(&req, 0, sizeof(req));
    req.messages = msgs;
    req.num_messages = 1;
    req.temperature = 0.2;
    /* reasoning models burn token budget on thinking before answering; 256
     * starves them into an empty content (seen with GLM-5.3-flash) */
    req.max_tokens = 4096;
    coa_llm_response resp;
    memset(&resp, 0, sizeof(resp));
    int rc = coa_llm_chat(llm, &req, &resp);
    free(b64);
    if (rc != 0) { free(resp.error); return -1; }
    *answer_out = resp.content;
    return 0;
}

int main(int argc, char **argv) {
    int real = 1, vision = 0;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--real") == 0) real = 1;
        else if (strcmp(argv[i], "--mock") == 0) real = 0;
        else if (strcmp(argv[i], "--vision") == 0) vision = 1;
        else { fprintf(stderr, "usage: %s [--mock|--real] [--vision]\n", argv[0]); return 2; }
    }

    coa_config cfg;
    memset(&cfg, 0, sizeof(cfg));
    cfg.state_root = "state-bench-gaia";
    cfg.workspace  = WS_ROOT;
    cfg.http_port  = 0;
    if (real) {
        cfg.provider = getenv("COA_LLM_PROVIDER");
        cfg.base_url = getenv("COA_LLM_BASE_URL");
        cfg.api_key  = getenv("COA_LLM_API_KEY");
        cfg.model    = getenv("COA_LLM_MODEL");
        if (!cfg.provider || !*cfg.provider) cfg.provider = "openai";
    } else {
        cfg.provider = "mock";
    }

    coa_ctx ctx;
    if (coa_init(&ctx, &cfg) != 0) {
        fprintf(stderr, "bench_gaia: coa_init failed (provider=%s)\n",
                cfg.provider ? cfg.provider : "?");
        return 1;
    }
    printf("cognitive-os-agent GAIA-style benchmark [%s] provider=%s model=%s\n\n",
           real ? "REAL" : "MOCK", ctx.provider ? ctx.provider : "?",
           getenv("COA_LLM_MODEL") ? getenv("COA_LLM_MODEL") : "?");

    coa_fs_mkdirs(WS_ROOT);
    make_text_fixtures();
    int docx_ok = run_python_fixtures();
    printf("fixtures: text=ok docx=%s\n\n", docx_ok ? "ok" : "SKIP");

    int l1_ok = 0, l1_n = 0, l2_ok = 0, l2_n = 0;
    int64_t t0 = coa_time_now_ms();
    for (int i = 0; i < N_TASKS; i++) {
        const gaia_task *t = &TASKS[i];
        if (t->need_docx && !docx_ok) {
            printf("  [L%d/%-10s] SKIP (docx fixture unavailable)\n", t->level, t->name);
            continue;
        }
        char *answer = NULL;
        int64_t s0 = coa_time_now_ms();
        int rc = coa_run(&ctx, t->prompt, &answer);
        int64_t lat = coa_time_now_ms() - s0;
        int ok = (rc == 0) && gaia_match(answer, t->expect);
        if (t->level == 1) { l1_n++; l1_ok += ok; } else { l2_n++; l2_ok += ok; }
        printf("  [L%d/%-10s] %s lat=%lldms answer=\"%.80s\" expect=%s\n",
               t->level, t->name, ok ? "PASS" : "FAIL", (long long)lat,
               answer ? answer : "(null)", t->expect);
        free(answer);
    }

    int vis_ok = -1; /* -1 = skipped */
    if (vision) {
        char *answer = NULL;
        int64_t s0 = coa_time_now_ms();
        int rc = vision_task(ctx.llm, &answer);
        int64_t lat = coa_time_now_ms() - s0;
        if (rc == 0) {
            vis_ok = gaia_match(answer, "7392");
            printf("  [V/vision-code] %s lat=%lldms answer=\"%.80s\" expect=7392\n",
                   vis_ok ? "PASS" : "FAIL", (long long)lat, answer);
        } else {
            printf("  [V/vision-code] FAIL lat=%lldms (image request failed - model may be text-only)\n",
                   (long long)lat);
        }
        free(answer);
    }

    int64_t total = coa_time_now_ms() - t0;
    coa_shutdown(&ctx);

    int tot_n = l1_n + l2_n, tot_ok = l1_ok + l2_ok;
    /* leaderboard-style scores (GAIA official reports percentages) */
    double l1_pct = l1_n ? 100.0 * l1_ok / l1_n : 0.0;
    double l2_pct = l2_n ? 100.0 * l2_ok / l2_n : 0.0;
    double avg_pct = tot_n ? 100.0 * tot_ok / tot_n : 0.0;
    printf("\n== scores (leaderboard format) ==\n");
    printf("  Average score   : %.2f%%  (%d/%d)\n", avg_pct, tot_ok, tot_n);
    printf("  Level 1 score   : %.2f%%  (%d/%d)\n", l1_pct, l1_ok, l1_n);
    printf("  Level 2 score   : %.2f%%  (%d/%d)\n", l2_pct, l2_ok, l2_n);
    if (vision) printf("  vision (L1-style) : %s\n",
                      vis_ok < 0 ? "skipped (--vision set but unavailable)" :
                      vis_ok ? "1/1" : "0/1");
    printf("  total wall time: %lldms\n", (long long)total);

    cJSON *j = cJSON_CreateObject();
    cJSON_AddNumberToObject(j, "avg_score_pct", avg_pct);
    cJSON_AddNumberToObject(j, "l1_score_pct", l1_pct);
    cJSON_AddNumberToObject(j, "l2_score_pct", l2_pct);
    cJSON_AddNumberToObject(j, "l1_ok", l1_ok);
    cJSON_AddNumberToObject(j, "l1_total", l1_n);
    cJSON_AddNumberToObject(j, "l2_ok", l2_ok);
    cJSON_AddNumberToObject(j, "l2_total", l2_n);
    cJSON_AddNumberToObject(j, "total_ok", tot_ok);
    cJSON_AddNumberToObject(j, "total_n", tot_n);
    if (vision) cJSON_AddNumberToObject(j, "vision_ok", vis_ok);
    cJSON_AddNumberToObject(j, "total_ms", (double)total);
    char *js = cJSON_PrintUnformatted(j);
    printf("  JSON: %s\n", js ? js : "{}");
    free(js);
    cJSON_Delete(j);
    return 0;
}
