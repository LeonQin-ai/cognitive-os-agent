/* ---- GAIA-style answer normalization ---- */
static int is_sep(int c) { return !isalnum(c); }

static void normalize(const char *in, char *out, size_t cap) {
    char step[2048];
    size_t o = 0;
    for (const char *p = in; *p && o + 1 < sizeof(step); p++) {
        unsigned char c = (unsigned char)*p;
        if (c >= 'A' && c <= 'Z') c += 32;
        step[o++] = is_sep(c) ? ' ' : (char)c;
    }
    step[o] = '\0';
    /* drop articles, collapse spaces */
    o = 0;
    char prev_space = 1;
    for (size_t i = 0; step[i] && o + 1 < cap; ) {
        if (step[i] == ' ') { if (!prev_space) out[o++] = ' '; prev_space = 1; i++; continue; }
        static const char *const arts[] = {"a ", "an ", "the "};
        int hit = 0;
        if (prev_space) {
            for (size_t a = 0; a < 3; a++) {
                size_t al = strlen(arts[a]);
                if (strncmp(&step[i], arts[a], al) == 0) { i += al; hit = 1; break; }
            }
        }
        if (hit) continue;
        out[o++] = step[i];
        prev_space = 0;
        i++;
    }
    while (o > 0 && out[o - 1] == ' ') o--;
    out[o] = '\0';
}

static int numeric_eq(const char *a, const char *b) {
    char *end = NULL;
    double x = strtod(a, &end);
    if (!end || *end != '\0' || end == a) return 0;
    double y = strtod(b, &end);
    if (!end || *end != '\0' || end == b) return 0;
    return x == y;
}

static int gaia_match(const char *answer, const char *expect) {
    if (!answer || !*answer || !expect) return 0;
    char na[2048], ne[512];
    normalize(answer, na, sizeof(na));
    normalize(expect, ne, sizeof(ne));
    if (!*ne) return 0;
    if (strcmp(na, ne) == 0) return 1;
    /* final non-empty line (harnesses commonly extract the last line) */
    const char *last = answer + strlen(answer);
    while (last > answer) {
        const char *nl = NULL;
        for (const char *q = answer; q < last; q++) if (*q == '\n') nl = q;
        const char *ls = nl ? nl + 1 : answer;
        const char *le = last;
        while (le > ls && isspace((unsigned char)le[-1])) le--;
        while (ls < le && isspace((unsigned char)*ls)) ls++;
        if (le > ls) {
            char line[1024];
            size_t n = (size_t)(le - ls);
            if (n >= sizeof(line)) n = sizeof(line) - 1;
            memcpy(line, ls, n);
            line[n] = '\0';
            char nl2[1024];
            normalize(line, nl2, sizeof(nl2));
            if (strcmp(nl2, ne) == 0) return 1;
            break; /* only the actual last line counts */
        }
        if (nl) last = nl; else break;
    }
    if (numeric_eq(na, ne)) return 1;
    return 0;
}

static void write_fixture(const char *rel, const char *content) {
    char full[1024];
    coa_path_resolve(full, sizeof(full), FIXDIR, rel);
    coa_fs_write_file(full, content, strlen(content));
}

