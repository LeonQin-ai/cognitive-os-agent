"""Embed the attachment processor so installed binaries need no source checkout."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root/'tools/attachment_extract.py').read_text(encoding='utf-8')
target = root/'include/api/attachment_extractor.h'
lines = ['/* GENERATED by tools/gen_attachment_extractor.py. */', '#pragma once',
         'static const char attachment_extractor[] =']
for line in source.splitlines(keepends=True):
    escaped = line.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n').replace('\r','\\r')
    lines.append('    "'+escaped+'"')
lines.append('    ;')
target.write_text('\n'.join(lines)+'\n', encoding='utf-8')
print('wrote',target)
